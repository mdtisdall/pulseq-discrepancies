#!/usr/bin/env python3
"""Generate docs/priorities.md, the records grouped by priority.

Usage: priorities.py [--check] [ROOT]

ROOT is the repository root (default: the parent of this script's directory).
Without --check, the script writes docs/priorities.md. With --check, it writes
nothing, and the exit status is 1 when docs/priorities.md is not the file that
the records give. The rules of the priorities are those of
docs/record-format.md, section 6.
"""

from __future__ import annotations

import sys
from pathlib import Path

from validate_records import FILE_NAME_RE, UNRANKED_STATUSES, read_front_matter

OUTPUT = Path("docs") / "priorities.md"
LEVELS = ("high", "medium", "low")
# In a group, the records are sorted by severity in this order, then by ID.
SEVERITY_ORDER = ("crash", "playback", "acceptance", "round-trip", "documentation")
WRITER_NAMES = {"matlab-pulseq": "MATLAB", "pypulseq": "pypulseq"}

HEADER = """\
<!-- Generated by scripts/priorities.py from the front matter of the records.
     Do not edit: change the `priority` field of a record, then run
     `nix develop --command uv run python scripts/priorities.py`. -->

# The discrepancies by priority

Each record has a priority (`docs/record-format.md`, section 6). When more
than one rule applies, the record has the highest:

| Priority | Rule |
|---|---|
| High | MATLAB Pulseq or pypulseq, at master, can write the condition, and a reader disagrees with the specification on such a file: it crashes, plays or reads another meaning, rejects a valid file, or accepts an invalid one. A writer that writes an invalid file also disagrees. |
| Medium | A reader crashes on a file that the specification allows. |
| Low | Neither: no writer at master writes the condition, and no reader crashes on a valid file. |

A record whose discrepancy master has fixed, but that the last release still
has, is in the last section, with the priority that it has in that release.
Records of status `duplicate` or `withdrawn` are not listed.
"""


def escape(text: str) -> str:
    """Text for one cell of a Markdown table."""
    return " ".join(str(text).split()).replace("|", "\\|")


def load(root: Path) -> list[dict]:
    """The front matter of each ranked record, with its file name."""
    records = []
    for path in sorted((root / "discrepancies").glob("DIS-*.md")):
        if not FILE_NAME_RE.match(path.name):
            continue
        data, error = read_front_matter(path.read_text(encoding="utf-8"))
        if error:
            raise ValueError(f"{path}: {error}")
        if data.get("status") in UNRANKED_STATUSES:
            continue
        if not isinstance(data.get("priority"), dict):
            raise ValueError(f"{path}: no priority (run validate_records.py)")
        data["_file"] = path.name
        records.append(data)
    return records


def sort_key(record: dict) -> tuple[int, str]:
    severity = record.get("severity")
    rank = SEVERITY_ORDER.index(severity) if severity in SEVERITY_ORDER else len(SEVERITY_ORDER)
    return rank, record["id"]


def link(record: dict) -> str:
    return f"[{record['id']}](../discrepancies/{record['_file']})"


def writers(record: dict) -> str:
    names = [WRITER_NAMES.get(w, w) for w in record["priority"].get("written_by") or []]
    return ", ".join(names) if names else "—"


def render(records: list[dict]) -> str:
    fixed = [r for r in records if r["priority"].get("fixed")]
    open_ = [r for r in records if not r["priority"].get("fixed")]
    groups = {level: sorted((r for r in open_ if r["priority"]["level"] == level), key=sort_key)
              for level in LEVELS}

    out = [HEADER, "| Priority | Records |", "|---|---|"]
    for level in LEVELS:
        out.append(f"| {level.capitalize()} | {len(groups[level])} |")
    out.append(f"| Fixed on master | {len(fixed)} |")
    out.append("")

    for level in LEVELS:
        out.append(f"## {level.capitalize()} priority")
        out.append("")
        if not groups[level]:
            out.append("None.")
            out.append("")
            continue
        out.append("| Record | Condition | Severity | Written by | Why |")
        out.append("|---|---|---|---|---|")
        for r in groups[level]:
            out.append(
                f"| {link(r)} | {escape(r['title'])} | {r['severity']} "
                f"| {writers(r)} | {escape(r['priority']['reason'])} |"
            )
        out.append("")

    out.append("## Fixed on master")
    out.append("")
    if not fixed:
        out.append("None.")
    else:
        out.append(
            "| Record | Condition | Priority in the release | Still in | Fixed by | Why |"
        )
        out.append("|---|---|---|---|---|---|")
        for r in sorted(fixed, key=lambda r: (LEVELS.index(r["priority"]["level"]), *sort_key(r))):
            p = r["priority"]
            out.append(
                f"| {link(r)} | {escape(r['title'])} | {p['level'].capitalize()} "
                f"| {escape(p['fixed']['last_release'])} | {escape(p['fixed']['by'])} "
                f"| {escape(p['reason'])} |"
            )
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    args = argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    if len(args) > 1:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    root = Path(args[0]) if args else Path(__file__).resolve().parent.parent
    try:
        text = render(load(root))
    except ValueError as e:
        print(f"priorities: {e}", file=sys.stderr)
        return 1
    path = root / OUTPUT
    if check:
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            print(
                f"priorities: {OUTPUT} is not up to date; run "
                "`nix develop --command uv run python scripts/priorities.py`",
                file=sys.stderr,
            )
            return 1
        print(f"priorities: {OUTPUT} is up to date")
        return 0
    path.write_text(text, encoding="utf-8")
    print(f"priorities: wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
